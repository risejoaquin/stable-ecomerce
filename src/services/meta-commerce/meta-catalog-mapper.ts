import type { Product, ProductVariant } from '../../types';
import type { CatalogProduct, CatalogVariant, MetaCatalogItem } from './catalog-types';
import { generateDefaultSku, generateVariantSku, normalizeSku } from '../../utils/sku-helpers';
import { parseVariantAttributes } from './variant-matcher';

const DEFAULT_STORE_URL = 'https://selfcaresinners.com';
const DEFAULT_BRAND = 'BLACK RELIC';

/**
 * Builds a canonical Meta Product Catalog item compatible with Instagram Shop,
 * Meta Commerce Manager, and Conversions API (CAPI) events.
 */
export function buildMetaCatalogItem(
  product: Product | CatalogProduct,
  variant?: ProductVariant | CatalogVariant | null,
  options: { baseUrl?: string; defaultBrand?: string } = {},
): MetaCatalogItem {
  const baseUrl = options.baseUrl || DEFAULT_STORE_URL;
  const brand = (product as any).brand || options.defaultBrand || DEFAULT_BRAND;

  // Compute stable parent SKU
  let parentSku = (product as any).sku || (product as any).defaultSku;
  if (!parentSku) {
    try {
      parentSku = generateDefaultSku(product as any);
    } catch {
      parentSku = `SKU-${product.id.toUpperCase().replace(/[^A-Z0-9]/g, '')}`;
    }
  }

  // Determine item identity & pricing
  let itemId: string = parentSku;
  let itemTitle: string = product.name;
  let itemPrice: number = product.price;
  let itemStock: number = product.stock;
  let size: string | undefined;
  let color: string | undefined;

  if (variant) {
    const parsed = parseVariantAttributes(variant as ProductVariant);
    if (parsed.size) size = parsed.size;
    if (parsed.color) color = parsed.color;

    // Stable variant SKU
    if (variant.sku) {
      try {
        itemId = normalizeSku(variant.sku);
      } catch {
        itemId = variant.sku.toUpperCase();
      }
    } else {
      try {
        itemId = generateVariantSku(product as any, variant as any);
      } catch {
        itemId = `${parentSku}-${(variant.id || 'VAR').toUpperCase().replace(/[^A-Z0-9]/g, '')}`;
      }
    }

    const varTitle = variant.name || (variant as any).title;
    itemTitle = `${product.name} - ${varTitle}`;
    if (typeof variant.price === 'number' && Number.isFinite(variant.price)) {
      itemPrice = variant.price;
    }
    itemStock = typeof variant.stock === 'number' ? variant.stock : 0;
  }

  const primaryImage = product.images && product.images.length > 0
    ? product.images[0]
    : `${baseUrl}/images/placeholder.webp`;

  const link = product.slug
    ? `${baseUrl}/product/${product.slug}`
    : `${baseUrl}/product/${product.id}`;

  return {
    id: itemId,
    item_group_id: product.id,
    title: itemTitle,
    description: (product as any).description || product.name,
    availability: itemStock > 0 ? 'in stock' : 'out of stock',
    condition: 'new',
    price: itemPrice.toFixed(2),
    currency: 'MXN',
    link,
    image_link: primaryImage,
    brand,
    ...(size ? { size } : {}),
    ...(color ? { color } : {}),
  };
}

/**
 * Parses inbound Meta Content ID from CAPI or Instagram Shop webhooks,
 * extracting potential product and variant lookup identifiers.
 */
export function parseMetaContentId(contentId: string): {
  normalizedContentId: string;
  isVariantSku: boolean;
  rawKey: string;
} {
  const trimmed = contentId.trim();
  let normalizedContentId: string;
  try {
    normalizedContentId = normalizeSku(trimmed);
  } catch {
    normalizedContentId = trimmed.toUpperCase();
  }

  // Variant SKUs generated by sku-helpers contain at least two segments (e.g. SKU-PRODUCT-VARIANT)
  const isVariantSku = normalizedContentId.split('-').length >= 3;

  return {
    normalizedContentId,
    isVariantSku,
    rawKey: trimmed,
  };
}
